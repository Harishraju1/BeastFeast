import type { ComponentRecord, SimStatus } from "@/lib/types";
import type { ParsedMasterList } from "./parse";

export interface CompletenessReport {
  totalSource: number;
  /** master-list records in the database */
  imported: number;
  /** platform additions: components added by BEAST FEAST that are not in the master list (counted separately) */
  platformAdditions: { id: string; name: string }[];
  missing: { section: number; item: number; name: string; line: number }[];
  duplicateIds: string[];
  duplicateSourceRefs: string[];
  crossListed: { name: string; ids: string[] }[];
  withImages: number;
  verifiedPinouts: number;
  genericPinouts: number;
  noPinout: number;
  with3dModels: number;
  proceduralModels: number;
  bySimStatus: Record<SimStatus, number>;
  byClass: Record<"A" | "B" | "C", number>;
  unverifiedSpecs: number;
  bySection: { number: number; title: string; source: number; imported: number }[];
  parserWarnings: string[];
  complete: boolean;
}

export function compareCatalogue(parsed: ParsedMasterList, allRecords: ComponentRecord[]): CompletenessReport {
  // Platform additions have no master-list source; they are reported separately and never hide a missing entry.
  const platform = allRecords.filter((r) => r.sources.length === 0);
  const records = allRecords.filter((r) => r.sources.length > 0);
  const key = (s: number, i: number, n: string) => `${s}#${i}#${n}`;
  const refCount = new Map<string, number>();
  for (const r of records) for (const s of r.sources) refCount.set(key(s.sectionNumber, s.itemNumber, s.sourceName), (refCount.get(key(s.sectionNumber, s.itemNumber, s.sourceName)) ?? 0) + 1);

  const missing = parsed.entries
    .filter((e) => !refCount.has(key(e.sectionNumber, e.itemNumber, e.name)))
    .map((e) => ({ section: e.sectionNumber, item: e.itemNumber, name: e.name, line: e.line }));
  const duplicateSourceRefs = [...refCount.entries()].filter(([, c]) => c > 1).map(([k]) => k);
  const idCount = new Map<string, number>();
  allRecords.forEach((r) => idCount.set(r.id, (idCount.get(r.id) ?? 0) + 1));
  const duplicateIds = [...idCount.entries()].filter(([, c]) => c > 1).map(([k]) => k);

  const seen = new Set<string>();
  const crossListed: CompletenessReport["crossListed"] = [];
  for (const r of records) {
    if (!r.crossListedWith.length || seen.has(r.id)) continue;
    const ids = [r.id, ...r.crossListedWith];
    ids.forEach((i) => seen.add(i));
    crossListed.push({ name: r.name, ids });
  }

  const bySimStatus: Record<SimStatus, number> = { green: 0, blue: 0, yellow: 0, grey: 0 };
  const byClass = { A: 0, B: 0, C: 0 };
  records.forEach((r) => {
    bySimStatus[r.simStatus]++;
    byClass[r.functionalityClass]++;
  });

  return {
    totalSource: parsed.entries.length,
    imported: records.length,
    platformAdditions: platform.map((r) => ({ id: r.id, name: r.name })),
    missing,
    duplicateIds,
    duplicateSourceRefs,
    crossListed,
    withImages: records.filter((r) => r.image).length,
    verifiedPinouts: records.filter((r) => r.pinoutStatus === "datasheet-referenced").length,
    genericPinouts: records.filter((r) => r.pinoutStatus === "generic-convention").length,
    noPinout: records.filter((r) => r.pinoutStatus === "not-available").length,
    with3dModels: records.filter((r) => r.model3d).length,
    proceduralModels: records.filter((r) => !r.model3d && r.functionalityClass !== "C").length,
    bySimStatus,
    byClass,
    unverifiedSpecs: records.filter((r) => r.verification === "unverified").length,
    bySection: parsed.sections.map((s) => ({
      number: s.number,
      title: s.title,
      source: parsed.entries.filter((e) => e.sectionNumber === s.number).length,
      imported: records.filter((r) => r.categoryNumber === s.number).length,
    })),
    parserWarnings: parsed.warnings,
    complete: missing.length === 0 && duplicateIds.length === 0 && duplicateSourceRefs.length === 0 && parsed.entries.length > 0,
  };
}

export function reportToMarkdown(rep: CompletenessReport, records: ComponentRecord[], sourceHash: string): string {
  const L: string[] = [];
  L.push("# COMPONENT CATALOGUE REPORT", "");
  L.push(`Generated by \`npm run catalogue:import\` from \`data/source/components-master-list.md\` (sha256 \`${sourceHash.slice(0, 16)}…\`).`, "");
  L.push(`**Status: ${rep.complete ? "COMPLETE — every numbered source entry is in the database" : "INCOMPLETE"}**`, "");
  L.push("| Metric | Value |", "| --- | --- |");
  L.push(`| Total source entries (numbered items, sections 1–16) | ${rep.totalSource} |`);
  L.push(`| Imported entries | ${rep.imported} |`);
  L.push(`| Platform additions (not in the master list, counted separately) | ${rep.platformAdditions.length}${rep.platformAdditions.length ? ` (${rep.platformAdditions.map((p) => p.name).join(", ")})` : ""} |`);
  L.push(`| Missing entries | ${rep.missing.length} |`);
  L.push(`| Duplicate database IDs | ${rep.duplicateIds.length} |`);
  L.push(`| Source entries imported twice | ${rep.duplicateSourceRefs.length} |`);
  L.push(`| Names listed in more than one section (kept as separate, cross-linked records) | ${rep.crossListed.length} groups |`);
  L.push(`| Entries with verified images | ${rep.withImages} |`);
  L.push(`| Pinouts entered from datasheets (awaiting admin sign-off) | ${rep.verifiedPinouts} |`);
  L.push(`| Function-standard (generic) pinouts | ${rep.genericPinouts} |`);
  L.push(`| No pinout yet | ${rep.noPinout} |`);
  L.push(`| Accurate 3D model files | ${rep.with3dModels} (all others use a labelled procedural representation) |`);
  L.push(`| Entries with unverified specifications | ${rep.unverifiedSpecs} |`, "");
  L.push("## Simulation coverage", "", "| Status | Meaning | Count |", "| --- | --- | --- |");
  L.push(`| GREEN | Fully simulated (used by the physics / electrical / code simulation) | ${rep.bySimStatus.green} |`);
  L.push(`| BLUE | Design & connection supported (pins, validation) | ${rep.bySimStatus.blue} |`);
  L.push(`| YELLOW | Visual / mechanical representation only | ${rep.bySimStatus.yellow} |`);
  L.push(`| GREY | Under development / unverified | ${rep.bySimStatus.grey} |`, "");
  L.push(`Functionality classes: A (electronic) ${rep.byClass.A}, B (mechanical) ${rep.byClass.B}, C (workshop) ${rep.byClass.C}.`, "");
  L.push("## Per section", "", "| # | Section | Source | Imported |", "| --- | --- | --- | --- |");
  rep.bySection.forEach((s) => L.push(`| ${s.number} | ${s.title} | ${s.source} | ${s.imported} |`));
  L.push("", "Section 17 (Competition-wise Component Identification) is a table, not a list of components; it is imported as the competition-compatibility rules applied to every record.", "");
  if (rep.missing.length) {
    L.push("## Missing entries", "");
    rep.missing.forEach((m) => L.push(`- Section ${m.section} item ${m.item}: ${m.name} (line ${m.line})`));
    L.push("");
  }
  L.push("## Cross-listed names", "");
  rep.crossListed.forEach((c) => L.push(`- ${c.name}: ${c.ids.map((i) => `\`${i}\``).join(", ")}`));
  L.push("", "## Verified / referenced records", "");
  records.filter((r) => r.verification === "datasheet-referenced").forEach((r) => L.push(`- ${r.name} (${r.simStatus.toUpperCase()})${r.datasheetUrl ? ` — ${r.datasheetUrl}` : ""}`));
  if (rep.parserWarnings.length) {
    L.push("", "## Parser warnings", "");
    rep.parserWarnings.forEach((w) => L.push(`- ${w}`));
  }
  L.push("", "## Full list", "", "| ID | Name | Section | Class | Status | Pinout | Verification |", "| --- | --- | --- | --- | --- | --- | --- |");
  records.forEach((r) => L.push(`| \`${r.id}\` | ${r.name} | ${r.categoryNumber}${r.subcategory ? ` / ${r.subcategory}` : ""} | ${r.functionalityClass} | ${r.simStatus} | ${r.pinoutStatus} | ${r.verification} |`));
  return L.join("\n") + "\n";
}
